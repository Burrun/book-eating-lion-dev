package com.bookeatinglion.ai.bot.chat;

/**
 * 상담방 상태.
 *
 * <p>대기열이 없다. "접속한 상담사가 0명이면 즉시 안내하고 종료" 이므로 줄을 세울 일이
 * 없고, {@link #WAITING} 은 <b>상담사가 있는데 아직 아무도 받지 않은 짧은 구간</b>만
 * 가리킨다. 그 구간에도 이름이 필요한 이유는 상담사 콘솔이 "받을 수 있는 방"을 알아야
 * 하기 때문이다.
 */
public enum ChatState {

    /** AI 가 응답 중. 방이 처음 열리면 여기서 시작한다. */
    BOT,

    /** 사용자가 상담사를 요청했고, 접속한 상담사가 있어 배정을 기다린다. */
    WAITING,

    /** 상담사가 받았다. 양방향 대화 구간. */
    LIVE,

    /** 종료. 방 해시는 잠시 남긴다 — 재접속한 클라이언트가 "없는 방"이 아니라 "끝난 방"을 봐야 한다. */
    CLOSED
}
