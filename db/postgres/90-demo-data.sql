-- =============================================================================
-- 로컬 데모 데이터 (클러스터 1개 — 4개 스키마)
--
-- 여기 있는 CREATE TABLE 은 db/postgres/01~04 의 "목표 스키마"가 아니라
-- **현재 JPA 엔티티 모양**이다. 전환 전 저장소에서도 같은 구조였다 —
-- 엔티티와 schema.sql 이 아직 정렬되지 않았고(예: members 는 엔티티가
-- cognito_sub 를 쓰는데 목표 스키마는 username/password 를 쓴다),
-- docker-compose 는 ddl-auto: update 로 뜨기 때문이다.
--
-- 그래서 01~04 파일은 마운트하지 않는다. 그것들은 Flyway 로 넘어갈 때의
-- 목표 스키마 참조본이고, 실제 로컬 기동은 이 파일 + ddl-auto 가 담당한다.
-- (전환 전에도 schema.sql 을 넣지 않고 1_demo_data.sql 만 넣었던 것과 같다)
--
-- 각 테이블이 어느 스키마에 들어가는지가 MSA 전환의 결과물이다.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- member_db
-- ---------------------------------------------------------------------------
-- member_id 는 auto-increment PK가 아니라 Cognito sub 값을 그대로 저장한다(PK 구조 변경,
-- Member.java 참고). 별도 cognito_sub 컬럼은 없다.
CREATE TABLE IF NOT EXISTS member_db.members (
    member_id    VARCHAR(255) PRIMARY KEY,
    email        VARCHAR(255) NOT NULL UNIQUE,
    name         VARCHAR(255) NOT NULL,
    nickname     VARCHAR(255) NOT NULL UNIQUE,
    phone_number VARCHAR(20),
    gender       VARCHAR(10),
    birth_date   DATE,
    role         VARCHAR(20) NOT NULL DEFAULT 'USER',
    grade        VARCHAR(20) NOT NULL DEFAULT 'BRONZE',
    point        INT NOT NULL DEFAULT 0,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

