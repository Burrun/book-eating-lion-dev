DECLARE
    r RECORD;
BEGIN
    FOR r IN
        SELECT schemaname, tablename,
               CASE schemaname
                   WHEN 'member_db'  THEN 'member_svc'
                   WHEN 'catalog_db' THEN 'catalog_svc'
                   WHEN 'order_db'   THEN 'order_svc'
                   WHEN 'ai_db'      THEN 'ai_svc'
               END AS owner
        FROM pg_tables
        WHERE schemaname IN ('member_db', 'catalog_db', 'order_db', 'ai_db')
    LOOP
        EXECUTE format('ALTER TABLE %I.%I OWNER TO %I', r.schemaname, r.tablename, r.owner);
    END LOOP;

    FOR r IN
        SELECT sequence_schema AS schemaname, sequence_name,
               CASE sequence_schema
                   WHEN 'member_db'  THEN 'member_svc'
                   WHEN 'catalog_db' THEN 'catalog_svc'
                   WHEN 'order_db'   THEN 'order_svc'
                   WHEN 'ai_db'      THEN 'ai_svc'
               END AS owner
        FROM information_schema.sequences
        WHERE sequence_schema IN ('member_db', 'catalog_db', 'order_db', 'ai_db')
    LOOP
        EXECUTE format('ALTER SEQUENCE %I.%I OWNER TO %I', r.schemaname, r.sequence_name, r.owner);
    END LOOP;
END $$;
