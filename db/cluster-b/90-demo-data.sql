-- 로컬 데모 데이터 (클러스터 B — ai_db)
--
-- lion_memories 는 엔티티 모양대로 만든다. embedding 은 vector(1024) 이며
-- pgvector 확장이 00-init.sql 에서 이미 설치됐다.

CREATE TABLE IF NOT EXISTS ai_db.lions (
    lion_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id    BIGINT NOT NULL UNIQUE,
    level        INT NOT NULL DEFAULT 1,
    exp          BIGINT NOT NULL DEFAULT 0,
    growth_stage VARCHAR(100) NOT NULL,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ai_db.lion_memories (
    lion_memory_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lion_id         BIGINT NOT NULL,
    book_id         BIGINT NOT NULL,
    book_title      VARCHAR(255),
    cover_url       VARCHAR(500),
    memo            TEXT,
    quote_text      TEXT,
    finished_at     TIMESTAMP,
    embedding       vector(1024),
    embedding_model VARCHAR(100),
    embedding_dim   INT,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ai_db.inquiries (
    inquiry_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id    BIGINT NOT NULL,
    nickname     VARCHAR(50),
    book_id      BIGINT,
    book_title   VARCHAR(255),
    title        VARCHAR(255) NOT NULL,
    content      TEXT NOT NULL,
    admin_answer TEXT,
    answered     BOOLEAN NOT NULL DEFAULT FALSE,
    answered_at  TIMESTAMP,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ai_db.faqs (
    faq_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category   VARCHAR(100) NOT NULL,
    question   VARCHAR(500) NOT NULL,
    answer     TEXT NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- member_id 는 member_db 의 값이지만 FK 가 없다. 클러스터가 아예 달라서
