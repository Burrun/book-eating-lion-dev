-- 소유권 이전 — GRANT 만으로는 ddl-auto 가 인덱스/제약을 못 붙인다.
-- (cluster-a/90-demo-data.sql 의 같은 블록과 이유가 같다)
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN SELECT tablename FROM pg_tables WHERE schemaname = 'ai_db' LOOP
        EXECUTE format('ALTER TABLE ai_db.%I OWNER TO ai_svc', r.tablename);
    END LOOP;

    FOR r IN SELECT sequence_name FROM information_schema.sequences WHERE sequence_schema = 'ai_db' LOOP
        EXECUTE format('ALTER SEQUENCE ai_db.%I OWNER TO ai_svc', r.sequence_name);
    END LOOP;
END $$;
